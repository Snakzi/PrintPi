def paused_job(runner, printer, tmp_path, seen, count: int = 60):
    """Start a print and pause it a few moves in; returns once the runner reports paused."""
    runner.start(gcode_file(tmp_path, moves(count)), name="part.gcode", file_id=1, estimated_seconds=60, bed=BED)
    assert wait_for(lambda: runner.state.line >= 5)
    runner.pause()
    assert wait_for(lambda: runner.state.state == "paused")


def test_pause_on_plain_marlin_parks_the_head_and_the_resume_puts_it_back(printer, runner, seen, tmp_path):
    paused_job(runner, printer, tmp_path, seen)
    sent = commands(printer)
    park = sent.index("M400")
    assert sent[park:park + 8] == ["M400", "M114", "M83", "G1 E-2 F2400", "G91", "G1 Z5 F600", "G90", "G1 X5.0 Y205.0 F6000"]
    assert any(state.activity == "pausing" for state in seen)
    assert printer.state.status == "paused"

    runner.resume()
    assert wait_for(lambda: runner.state.state == "finished", timeout=15.0)
    sent = commands(printer)
    back = sent.index("G90", park + 8)
    fake = printer._port
    x, y = fake.position["X"], fake.position["Y"]  # wherever the file ends, the head went back before continuing
    assert sent[back].startswith("G90") and sent[back + 1].startswith("G1 X") and sent[back + 2].startswith("G1 Z")
    assert sent[back + 3:back + 5] == ["M83", "G1 E2 F2400"]
    assert sent[back + 5].startswith("G92 E")
    assert sent[back + 6:back + 9] == ["M82", "G90", "G1 F6000"]
    moves_sent = [command for command in sent if command.startswith("G1 X") and " E" in command]
    assert moves_sent == moves(60).splitlines()
    assert any(state.activity == "resuming" for state in seen)
    assert runner.state.activity is None
    assert runner.state.error is None and (x, y) != (5.0, 205.0)


def test_pause_on_buddy_uses_m601_and_the_resume_waits_for_the_printer(seen, tmp_path):
    printer = prusa_printer("buddy")
    runner = runner_for(printer, seen)
    fake = printer._port
    fake.resume_delay = None  # the host action comes when the test says so
    try:
        paused_job(runner, printer, tmp_path, seen)
        sent = commands(printer)
        assert sent[-1] == "M601" and "M400" not in sent
        assert fake.paused

        runner.resume()
        assert wait_for(lambda: runner.state.activity == "resuming")
        assert wait_for(lambda: commands(printer)[-1] == "M602")
        time.sleep(0.2)
        assert commands(printer)[-1] == "M602"  # nothing streams until the printer reports the resume
        assert runner.state.state == "printing"

        fake.host_action("resume")
        assert wait_for(lambda: runner.state.state == "finished", timeout=15.0)
        sent = commands(printer)
        assert sent.count("M601") == 1 and sent.count("M602") == 1
        assert [command for command in sent if command.startswith("G1 X")] == moves(60).splitlines()
    finally:
        runner.stop()
        printer.disconnect()


def test_a_pause_and_resume_at_the_buddy_screen_drive_the_job(seen, tmp_path):
    printer = prusa_printer("buddy")
    runner = runner_for(printer, seen)
    fake = printer._port
    try:
        runner.start(gcode_file(tmp_path, moves(60)), name="part.gcode", file_id=1, estimated_seconds=60, bed=BED)
        assert wait_for(lambda: runner.state.line >= 5)
        fake.host_action("pause")  # Buddy has parked already and tells the host
        assert wait_for(lambda: runner.state.state == "paused")
        assert commands(printer)[-1] == "M601"  # harmless on a printer that is paused already

        fake.paused = False
        fake.host_action("resume")  # reheated and back in position, the screen's resume
        assert wait_for(lambda: runner.state.state == "finished", timeout=15.0)
        assert "M602" not in commands(printer)
        assert [command for command in commands(printer) if command.startswith("G1 X")] == moves(60).splitlines()
    finally:
        runner.stop()
        printer.disconnect()


