def test_streams_the_file_and_finishes(printer, runner, seen, tmp_path):
    path = gcode_file(tmp_path, SAMPLE)
    job = runner.start(path, name="Benchy.gcode", file_id=7, estimated_seconds=600)
    assert job.state == "printing" and job.name == "Benchy.gcode" and job.file_id == 7
    assert printer.state.status == "printing"

    assert wait_for(lambda: runner.state.state == "finished")
    sent = commands(printer)
    assert sent[-1] == "M400"  # the end waits for the last moves before the job is over
    sent = sent[:-1]
    assert sent[-6:] == ["G1 X10 Y10 F3000", "G1 X20 Y10 E1", "G1 X20 Y20 E2", "G1 X10 Y20 E3", "M73 P100 R0", "M105"] or \
        sent[-5:] == ["G1 X10 Y10 F3000", "G1 X20 Y10 E1", "G1 X20 Y20 E2", "G1 X10 Y20 E3", "M73 P100 R0"]
    assert not any(command.startswith(";") for command in sent)

    final = runner.state
    assert final.progress == 1.0
    assert final.line == final.total_lines == 13
    assert final.layer == final.total_layers == 2
    assert final.bytes_sent == final.total_bytes == scan_file(path)[2]
    assert final.finished_at is not None and final.elapsed > 0
    assert final.remaining == 0.0 and final.error is None
    assert printer.state.status == "idle"
    assert [state.state for state in seen][0] == "printing"
    assert seen[-1].state == "finished"
    assert any(state.layer == 1 for state in seen) and any(state.layer == 2 for state in seen)


