def test_pause_holds_the_stream_and_is_not_counted_as_print_time(printer, runner, tmp_path):
    runner.start(gcode_file(tmp_path, "G4 S30\n" + moves(150)))
    runner.pause()
    assert wait_for(lambda: runner.state.state == "paused")
    assert printer.state.status == "paused"
    with pytest.raises(JobError, match="no print is running"):
        runner.pause()

    sent_before = len(commands(printer))
    time.sleep(0.3)
    assert len(commands(printer)) == sent_before
    paused_job = runner.state
    time.sleep(0.1)
    assert runner.state.elapsed == pytest.approx(paused_job.elapsed, abs=0.02)

    started = time.monotonic()
    runner.resume()
    assert wait_for(lambda: runner.state.state == "finished")
    assert runner.state.elapsed < (time.monotonic() - started) + 0.35
    # Every line went out exactly once, the pause only delayed them (its park script aside).
    file_lines = [c for c in commands(printer)[4:] if c == "G4 S30" or (c.startswith("G1 X") and " E" in c)]
    assert file_lines == ["G4 S30", *moves(150).splitlines()]
    with pytest.raises(JobError, match="not paused"):
        runner.resume()


