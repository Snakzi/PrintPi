def test_remaining_time_estimates(printer, runner):
    job = JobState(name="x", path="x", estimated_seconds=1000)
    job.progress = 0.01
    # Before the first layer the slicer's figure stands still: heating is not part of it.
    assert runner._estimate_remaining(job, 100.0) == (1000.0, "slicer")
    runner._print_started_at = 0.0
    assert runner._estimate_remaining(job, 100.0) == (900.0, "slicer")
    job.progress = 0.5
    assert runner._estimate_remaining(job, 100.0) == (pytest.approx(500.0), "slicer")
    job.estimated_seconds = None
    assert runner._estimate_remaining(job, 100.0) == (pytest.approx(100.0), "progress")
    job.progress = 0.01
    assert runner._estimate_remaining(job, 100.0) == (None, None)
    job.estimated_seconds = 50
    assert runner._estimate_remaining(job, 100.0) == (0.0, "slicer")


def test_m73_remaining_holds_before_the_first_layer_and_follows_the_pace_after(printer, runner):
    job = JobState(name="x", path="x")
    runner._m73 = (7200.0, 10.0, None)  # seen with 10 s elapsed, slicer at P0
    assert runner._estimate_remaining(job, 200.0) == (7200.0, "m73")

    runner._print_started_at = 180.0
    runner._m73 = (3600.0, 180.0, None)
    assert runner._estimate_remaining(job, 240.0) == (pytest.approx(3540.0), "m73")

    # Halfway by the slicer's clock (P50 R30 → it expected 1800 s) after 3600 s of real printing: twice as slow.
    runner._m73 = (1800.0, 180.0 + 3600.0, 1800.0)
    assert runner._estimate_remaining(job, 180.0 + 3600.0 + 60.0) == (pytest.approx(3540.0), "m73")
    assert pace_factor(3600.0, 1800.0) == 2.0
    assert pace_factor(60.0, 30.0) == 1.0  # too early to judge
    assert pace_factor(9000.0, 1800.0) == 2.5  # clamped

    # The slicer's estimate ran out while the print goes on: the pace by progress takes over.
    runner._m73 = (60.0, 1000.0, None)
    job.progress = 0.98
    remaining, source = runner._estimate_remaining(job, 2000.0)
    assert source == "progress" and remaining == pytest.approx(2000.0 / 0.98 - 2000.0)


