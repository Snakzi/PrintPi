def wait_for(predicate, timeout: float = 5.0) -> bool:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if predicate():
            return True
        time.sleep(0.01)
    return predicate()


@pytest.fixture
def printer():
    p = Printer(FAST, connect_timeout=1.0, ok_timeout=5.0, temperature_interval=1.0)
    p.connect()
    yield p
    if p._port is not None:
        p.disconnect()


@pytest.fixture
def seen() -> list[JobState]:
    return []


def runner_for(printer: Printer, seen: list[JobState]) -> SerialJobRunner:
    """A runner on the printer that also hears the printer's host actions, as the bridge wires it."""
    r = SerialJobRunner(lambda: printer, on_state=seen.append, publish_interval=0.0)
    printer.on_action = r.handle_action
    return r


@pytest.fixture
def runner(printer, seen):
    r = runner_for(printer, seen)
    yield r
    r.stop()


def gcode_file(tmp_path: Path, text: str, name: str = "part.gcode") -> str:
    path = tmp_path / name
    path.write_text(text)
    return str(path)


def commands(printer: Printer) -> list[str]:
    return printer._port.commands


def moves(count: int) -> str:
    return "".join(f"G1 X{i % 20} Y{i % 7} E{i * 0.1:.1f} F6000\n" for i in range(count))


def test_scan_file_counts_lines_layer_markers_and_command_bytes(tmp_path):
    command_bytes = sum(len(line) + 1 for line in SAMPLE.splitlines() if line.strip() and not line.startswith(";"))
    assert scan_file(gcode_file(tmp_path, SAMPLE)) == (13, 2, command_bytes)
    assert scan_file(gcode_file(tmp_path, "G28\nG1 X1", "no-newline.gcode")) == (2, 0, 9)
    assert scan_file(gcode_file(tmp_path, ";LAYER:0\nG1 X1\n;LAYER:1\nG1 X2\n", "cura.gcode")) == (4, 2, 12)
    assert scan_file(gcode_file(tmp_path, "G28\n; trailing comment", "comment-tail.gcode")) == (2, 0, 4)
    assert scan_file(gcode_file(tmp_path, "", "empty.gcode")) == (0, 0, 0)


def test_scan_file_handles_lines_across_chunks(tmp_path, monkeypatch):
    monkeypatch.setattr("printpi_daemon.job._SCAN_CHUNK", 7)
    text = "; header comment\n;LAYER_CHANGE\nG1 X10 Y10 E1 ; note\n\n;LAYER_CHANGE\nG1 X20\n"
    assert scan_file(gcode_file(tmp_path, text)) == (6, 2, len("G1 X10 Y10 E1 ; note\n") + len("G1 X20\n"))


def test_progress_ignores_the_comment_blocks_a_slicer_embeds(printer, runner, tmp_path):
    # A thumbnail header the size of the whole print must not move the bar before the first command.
    thumbnail = "; thumbnail begin 480x240 4000\n" + "; " * 20 + ("; " + "A" * 76 + "\n") * 60 + "; thumbnail end\n"
    text = thumbnail + "G28\nG4 S100\n" + moves(20)
    runner.start(gcode_file(tmp_path, text))
    # The dwell holds the stream on line 64, right after the header was skipped.
    assert wait_for(lambda: runner.state.line >= 63)
    job = runner.state
    assert job.total_bytes == len(text) - len(thumbnail)
    assert job.progress < 0.05
    assert wait_for(lambda: runner.state.state == "finished")
    assert runner.state.bytes_sent == runner.state.total_bytes


